-- Weekly Orbit Planner tables. Postgres runs this the first time the database volume is created.

CREATE TABLE IF NOT EXISTS orbit_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_key  VARCHAR(40)  NOT NULL,
    username      VARCHAR(40)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_orbit_user_username_key UNIQUE (username_key)
);

CREATE TABLE IF NOT EXISTS orbit_member_week (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    week_number INTEGER      NOT NULL,
    start_date  DATE,
    end_date    DATE,
    program     VARCHAR(500),
    CONSTRAINT uk_member_week UNIQUE (user_id, week_number)
);

CREATE TABLE IF NOT EXISTS orbit_member_day (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT,
    week_number      INTEGER        NOT NULL,
    day_index        INTEGER        NOT NULL,
    theme            VARCHAR(4000),
    notes            VARCHAR(8000),
    elapsed_seconds  DOUBLE PRECISION NOT NULL DEFAULT 0,
    kept_seconds     DOUBLE PRECISION NOT NULL DEFAULT 0,
    target_seconds   DOUBLE PRECISION NOT NULL DEFAULT 14400,
    running          BOOLEAN        NOT NULL DEFAULT FALSE,
    running_since    TIMESTAMP(6) WITH TIME ZONE,
    completed        BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_member_day UNIQUE (user_id, week_number, day_index)
);

CREATE TABLE IF NOT EXISTS orbit_member_detail (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    week_number INTEGER       NOT NULL,
    day_index   INTEGER       NOT NULL,
    detail_text VARCHAR(2000) NOT NULL,
    done        BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order  INTEGER       NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS orbit_achievement (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    week_number INTEGER      NOT NULL,
    day_index   INTEGER      NOT NULL,
    week_start  DATE,
    day_date    DATE,
    day_name    VARCHAR(20)  NOT NULL,
    theme       VARCHAR(4000),
    finished_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_achievement UNIQUE (user_id, week_number, day_index, week_start)
);

CREATE TABLE IF NOT EXISTS orbit_history_week (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    week_number INTEGER     NOT NULL,
    start_date  DATE        NOT NULL,
    end_date    DATE        NOT NULL,
    program     VARCHAR(500),
    CONSTRAINT uk_history_week UNIQUE (user_id, start_date)
);

CREATE TABLE IF NOT EXISTS orbit_history_day (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history_week_id   BIGINT       NOT NULL,
    user_id           BIGINT       NOT NULL,
    day_index         INTEGER      NOT NULL,
    day_name          VARCHAR(20)  NOT NULL,
    day_date          DATE,
    theme             VARCHAR(4000),
    notes             VARCHAR(8000),
    completed         BOOLEAN        NOT NULL DEFAULT FALSE,
    elapsed_seconds   DOUBLE PRECISION NOT NULL DEFAULT 0,
    details_snapshot  TEXT,
    CONSTRAINT uk_history_day UNIQUE (history_week_id, day_index)
);

CREATE TABLE IF NOT EXISTS orbit_theme_plan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    theme_key   VARCHAR(500) NOT NULL,
    theme_label    VARCHAR(500) NOT NULL,
    plan_text      TEXT,
    logged_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
    CONSTRAINT uk_theme_plan UNIQUE (user_id, theme_key)
);

CREATE TABLE IF NOT EXISTS orbit_plan_checkpoint (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id          BIGINT        NOT NULL,
    user_id          BIGINT        NOT NULL,
    checkpoint_text  VARCHAR(500)  NOT NULL,
    done             BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order       INTEGER       NOT NULL DEFAULT 0,
    aim_on           DATE
);
